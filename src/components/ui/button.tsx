import * as React from "react";
import { Slot } from "@radix-ui/react-slot";
import { cva, type VariantProps } from "class-variance-authority";
import { cn } from "@/lib/utils";

const buttonVariants = cva(
  "inline-flex items-center justify-center gap-2 whitespace-nowrap rounded-full text-sm font-semibold transition-all focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 [&_svg]:size-4 [&_svg]:shrink-0 active:scale-[0.98]",
  {
    variants: {
      variant: {
        default: "bg-forest text-white shadow-soft hover:bg-forest-700 dark:bg-mint dark:text-forest dark:hover:bg-mint/90",
        eco: "bg-eco text-white shadow-soft hover:bg-eco-light",
        destructive: "bg-status-critical text-white shadow-soft hover:bg-status-critical/90",
        outline: "border border-forest/15 bg-card hover:bg-mint-soft dark:border-white/15 dark:hover:bg-white/5",
        secondary: "bg-mint-soft text-forest hover:bg-mint/60 dark:bg-white/10 dark:text-mint",
        ghost: "hover:bg-mint-soft dark:hover:bg-white/5",
        link: "text-eco underline-offset-4 hover:underline",
      },
      size: {
        default: "h-10 px-5",
        sm: "h-8 px-3.5 text-xs",
        lg: "h-12 px-7 text-base",
        icon: "h-10 w-10",
      },
    },
    defaultVariants: { variant: "default", size: "default" },
  },
);

export interface ButtonProps extends React.ButtonHTMLAttributes<HTMLButtonElement>, VariantProps<typeof buttonVariants> {
  asChild?: boolean;
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(({ className, variant, size, asChild = false, ...props }, ref) => {
  const Comp = asChild ? Slot : "button";
  return <Comp className={cn(buttonVariants({ variant, size, className }))} ref={ref} {...props} />;
});
Button.displayName = "Button";

export { Button, buttonVariants };
